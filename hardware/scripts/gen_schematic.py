"""Generate hardware/sub-eq.kicad_sch from circuit.py (label-based schematic)."""
import os, uuid, math
from sexp import dump, Sym
import symlib
import circuit

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", circuit.PROJECT + ".kicad_sch")
NS = uuid.UUID("6f1c2b1e-6f0e-4f4c-9b1a-2a7d3c0a5e11")
ROOT = str(uuid.uuid5(NS, "root"))
STUB = 2.54


def uid(*k):
    return str(uuid.uuid5(NS, "/".join(str(x) for x in k)))


def S(x):
    return Sym(x)


def font(hide=False, justify=None):
    e = [S("effects"), [S("font"), [S("size"), 1.27, 1.27]]]
    if justify:
        e.append([S("justify")] + [S(j) for j in justify])
    if hide:
        e.append([S("hide"), S("yes")])
    return e


def prop(name, value, x, y, hide=False):
    return [S("property"), name, value, [S("at"), x, y, 0], font(hide)]


def r(v):
    return round(v / 0.0254) * 0.0254 if False else round(v, 3)


def check_collisions(segs):
    def on(pt, s):
        (x1, y1), (x2, y2) = s[0], s[1]
        x, y = pt
        if abs((x2 - x1) * (y - y1) - (y2 - y1) * (x - x1)) > 1e-6:
            return False
        return min(x1, x2) - 1e-6 <= x <= max(x1, x2) + 1e-6 and min(y1, y2) - 1e-6 <= y <= max(y1, y2) + 1e-6
    bad = set()
    for s in segs:
        for t in segs:
            if s is not t and s[4] != t[4] and (on(t[0], s) or on(t[1], s)):
                bad.add((s[2], s[3], s[4], t[2], t[3], t[4]))
    if bad:
        raise SystemExit("schematic stub collisions: %s" % sorted(bad))


def main():
    parts = circuit.PARTS
    merged = circuit.merged()
    lib_ids = sorted({p["lib_id"] for p in parts})
    body = [S("kicad_sch"), [S("version"), 20250114], [S("generator"), "eeschema"],
            [S("generator_version"), "9.0"], [S("uuid"), ROOT], [S("paper"), circuit.PAPER],
            [S("title_block"), [S("title"), circuit.TITLE],
             [S("date"), "2026-11-10"], [S("rev"), circuit.REV],
             [S("comment"), 1, "Generated by hardware/scripts/gen_schematic.py from circuit.py"]]]
    body.append([S("lib_symbols")] + [symlib.load(l) for l in lib_ids])

    items = []
    segs = []
    for p in parts:
        lib_id = p["lib_id"]
        unit = p["unit"] or 1
        x0, y0 = p["at"]
        m = merged[p["ref"]]
        value = m["value"]
        fp = m["fp"] or ""
        is_flag = p["ref"].startswith("#")
        su = uid("sym", p["ref"], unit)
        allpins = symlib.pins(lib_id)
        unit_pins = {num: v for (u, num), v in allpins.items() if u in (0, unit)}
        inst = [S("symbol"), [S("lib_id"), lib_id], [S("at"), x0, y0, 0], [S("unit"), unit],
                [S("exclude_from_sim"), S("no")], [S("in_bom"), S("no") if (is_flag or p.get("role") in ("hole", "shield")) else S("yes")],
                [S("on_board"), S("no") if is_flag else S("yes")], [S("dnp"), S("no")],
                [S("uuid"), su],
                prop("Reference", p["ref"], x0 + 3.81, y0 - 6.35, hide=is_flag),
                prop("Value", value, x0 + 3.81, y0 + 6.35),
                prop("Footprint", fp, x0, y0, hide=True),
                prop("Datasheet", "~", x0, y0, hide=True)]
        if m.get("mpn"):
            inst.append(prop("MPN", m["mpn"], x0, y0, hide=True))
        for num in sorted(unit_pins):
            inst.append([S("pin"), num, [S("uuid"), uid("pin", p["ref"], num)]])
        inst.append([S("instances"), [S("project"), circuit.PROJECT,
                                      [S("path"), "/" + ROOT, [S("reference"), p["ref"]], [S("unit"), unit]]]])
        items.append(inst)

        for num, (px, py, ang, name, etype) in sorted(unit_pins.items()):
            ex, ey = x0 + px, y0 - py
            net = p["pins"].get(num)
            if net is None:
                if not is_flag:
                    items.append([S("no_connect"), [S("at"), r(ex), r(ey)], [S("uuid"), uid("nc", p["ref"], num)]])
                continue
            a = math.radians(ang)
            dx, dy = p.get("stubs", {}).get(num, (-round(math.cos(a)), round(math.sin(a))))
            sx, sy = ex + dx * STUB, ey + dy * STUB
            segs.append(((ex, ey), (sx, sy), p["ref"], num, net))
            items.append([S("wire"), [S("pts"), [S("xy"), r(ex), r(ey)], [S("xy"), r(sx), r(sy)]],
                          [S("stroke"), [S("width"), 0], [S("type"), S("default")]],
                          [S("uuid"), uid("w", p["ref"], num)]])
            langle = {(1, 0): 0, (-1, 0): 180, (0, -1): 90, (0, 1): 270}[(dx, dy)]
            just = ["left", "bottom"] if langle in (0, 90) else ["right", "bottom"]
            items.append([S("label"), net, [S("at"), r(sx), r(sy), langle], font(justify=just),
                          [S("uuid"), uid("lbl", p["ref"], num)]])

    check_collisions(segs)
    notes = [(t, 15.24, 35.56 + 22.86 * row - 11.43) for t, row in circuit.NOTES]
    for i, (t, x, y) in enumerate(notes):
        items.append([S("text"), t, [S("exclude_from_sim"), S("no")], [S("at"), x, y, 0],
                      [S("effects"), [S("font"), [S("size"), 2, 2], [S("bold"), S("yes")]],
                       [S("justify"), S("left"), S("bottom")]], [S("uuid"), uid("note", i)]])

    body += items
    body.append([S("sheet_instances"), [S("path"), "/", [S("page"), "1"]]])
    body.append([S("embedded_fonts"), S("no")])
    with open(OUT, "w") as f:
        f.write(dump(body) + "\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
